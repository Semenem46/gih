"""patch_query_engine_prompts.py — усиливает AI-промпты в query_engine.py.

Исправляет:
  1. qualify_message_for_niche — теперь жёстко отсекает аналитику, новости,
     объявления о найме чужих компаний, экспертные комментарии, образовательные посты.
  2. analyze_niche — учитывает опечатки и возвращает пустые keywords если не понимает.

Идемпотентен: если уже пропатчен — не падает.
"""
from __future__ import annotations
import shutil
import sys
import time
from pathlib import Path

TARGET = Path("/root/leadbot/query_engine.py")

if not TARGET.exists():
    print(f"ERROR: не нашёл {TARGET}")
    sys.exit(1)

content = TARGET.read_text(encoding="utf-8")

# Бэкап
backup = TARGET.parent / f"{TARGET.name}.bak_{int(time.time())}"
shutil.copy(TARGET, backup)
print(f"💾 Бэкап: {backup}")

# ── Патч #1: qualify_message_for_niche ──────────────────────────────────────
old_qualify = """ОЦЕНИ score 0-100:
[90-100] ГОРЯЧИЙ-ЯВНЫЙ: автор прямо ищет такую услугу как у клиента, готов к контакту.
[75-89]  ГОРЯЧИЙ-НЕЯВНЫЙ: автор описывает боль/задачу которая ОДНОЗНАЧНО решается услугой клиента, видно что он lpr (владелец/руководитель), есть бюджет.
[50-74]  ТЁПЛЫЙ: интерес есть, но боль размыта или это не основная услуга клиента.
[0-49]   НЕЦЕЛЕВОЙ: не подходит, спам, продавец услуги, общий разговор, инфоцыган, соискатель работы.

ОТКЛОНЯЙ (score < 50) если:
- Автор сам ПРОДАЁТ услугу (а не покупает)
- Резюме / поиск работы / ищу проект
- Инфоцыганские курсы по теме
- Гео не совпадает (если клиент локально)
- Это бот / реклама / новостной канал"""

new_qualify = """ОЦЕНИ score 0-100:
[90-100] ГОРЯЧИЙ-ЯВНЫЙ: автор от ПЕРВОГО лица прямо ищет такую услугу как у клиента, готов к контакту.
[75-89]  ГОРЯЧИЙ-НЕЯВНЫЙ: автор от ПЕРВОГО лица описывает СВОЮ боль/задачу которая решается услугой клиента, явно lpr (владелец/руководитель).
[50-74]  ТЁПЛЫЙ: интерес есть, но боль размыта или это не основная услуга клиента.
[0-49]   НЕЦЕЛЕВОЙ: не подходит.

═══ КЛЮЧЕВОЙ ПРИНЦИП ═══

ЛИД = ЗАКАЗЧИК ИЩЕТ ИСПОЛНИТЕЛЯ ОТ ПЕРВОГО ЛИЦА.
Должны быть фразы: "я ищу", "нам нужен", "мы ищем", "хочу заказать", "посоветуйте подрядчика", "кто может сделать".

═══ ЖЁСТКО ОТКЛОНЯЙ (score 0-30) ═══

❌ ВАКАНСИЯ / ОБЪЯВЛЕНИЕ О НАЙМЕ от лица сторонней компании:
   "Застройщик X ищет директора по продажам"
   "ООО Туч ищет руководителя"
   "Компания N ищет сотрудника в штат"
   → Это объявление о найме, НЕ запрос подрядчика.

❌ АНАЛИТИКА / ОБЗОР РЫНКА (экспертный пост):
   Признаки: "О чём это говорит?", "Это сигнал", "Тенденция", "Функция X становится...",
             "В 2026 будет...", "Показательная ситуация", "Рынок переходит к...",
             "Это означает что...", "Делаем выводы".
   → Это разбор/мнение, НЕ запрос услуги.

❌ НОВОСТЬ / ПРЕСС-РЕЛИЗ:
   Признаки: третье лицо, имена компаний без личного "я",
             объявления о событиях, "сегодня X сделал Y".

❌ ОБРАЗОВАТЕЛЬНЫЙ ПОСТ:
   "3 ошибки", "5 советов", "Как настроить...", "Чек-лист", "Гайд",
   "Что делать если...".

❌ АВТОР САМ ПРОДАЁТ УСЛУГУ (а не покупает):
   "делаю", "оказываю", "беру проекты", "пишите в ЛС за услугами",
   "веду", "настраиваю".

❌ РЕЗЮМЕ / ПОИСК РАБОТЫ:
   "ищу проект", "буду рад заказам", "опыт N лет", "моё портфолио".

❌ ИНФОЦЫГАНСКИЕ КУРСЫ:
   "обучу за 30 дней", "наставничество", "мастер-группа", "приходи на марафон".

❌ Бот / реклама / новостной канал.
❌ Гео не совпадает (если клиент локально)."""

if old_qualify in content:
    content = content.replace(old_qualify, new_qualify)
    print("✓ qualify_message_for_niche промпт обновлён")
elif new_qualify in content:
    print("· qualify-промпт уже обновлён")
else:
    print("⚠️  не нашёл старый qualify-промпт. Возможно файл отличается. Бэкап в безопасности.")

# ── Патч #2: analyze_niche (опечатки) ───────────────────────────────────────
old_analyze = """ВАЖНО:
- Keywords должны покрывать синонимы и формы слов. Например для «ремонт квартир»: ["ремонт", "отделк", "ремонтн", "под ключ", "квартир", "отделочн", "косметическ ремонт"].
- Если ниша широкая (e.g. "услуги"), keywords должны помочь сузить.
- Если упомянут город, обязательно добавь его в keywords тоже."""

new_analyze = """ВАЖНО:
- Keywords должны покрывать синонимы и формы слов. Например для «ремонт квартир»: ["ремонт", "отделк", "ремонтн", "под ключ", "квартир", "отделочн", "косметическ ремонт"].
- Если ниша широкая (e.g. "услуги"), keywords должны помочь сузить.
- Если упомянут город, обязательно добавь его в keywords тоже.
- Если в тексте есть очевидная опечатка (директорог→директолог, дирктолог→директолог, сматарт→стартап) — исправь и используй каноническую форму.
- Если ты НЕ ПОНИМАЕШЬ нишу (бессмысленный/слишком общий текст без контекста типа "лиды", "продажа", "клиенты", или абракадабра) — верни keywords: [] и niche_canonical: "не понял"."""

if old_analyze in content:
    content = content.replace(old_analyze, new_analyze)
    print("✓ analyze_niche промпт обновлён")
elif new_analyze in content:
    print("· analyze-промпт уже обновлён")
else:
    print("⚠️  не нашёл старый analyze-промпт. Возможно файл отличается.")

TARGET.write_text(content, encoding="utf-8")
print(f"\n✅ patched: {TARGET}")
print("Откат: cp", backup, TARGET)
